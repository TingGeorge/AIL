import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const mvpDirectory = path.resolve(scriptDirectory, '..');
const snapshotPath = path.join(
  mvpDirectory,
  'data',
  'yuanshan-open-data.snapshot.json',
);
const fullSeedPath = path.join(
  mvpDirectory,
  'drizzle',
  '0005_yuanshan_catalog_seed_20260905.sql',
);
const outputDirectory = path.join(mvpDirectory, 'sites-drizzle');
const outputPath = path.join(outputDirectory, '0004_catalog_seed.sql');

// Sites applies migrations while publishing. Keep this bootstrap deliberately
// compact, then let the runtime overlay refresh YouBike and Culture data.
const providerLimits = new Map([
  ['TAIPEI_RESTAURANT_REGISTRY', 30],
  ['TAIPEI_PHARMACY', 25],
  ['TAIPEI_DRINKING_WATER', 20],
  ['TAIPEI_FREE_WIFI', 20],
  ['TAIPEI_COOLING_SPOT', 15],
  ['TAIPEI_YOUBIKE', 30],
  ['MOC_CULTURE_NEARBY', 10],
  ['EXPOPARK', 1],
]);
const opportunityLimit = 40;
const maxMigrationBytes = 2_000_000;
const maxStatementBytes = 100_000;

const snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'));
const fullSeedLines = readFileSync(fullSeedPath, 'utf8').split(/\r?\n/);

const selectedPlaces = [];
for (const [provider, limit] of providerLimits) {
  selectedPlaces.push(
    ...snapshot.places
      .filter((place) => place.provider === provider)
      .sort((left, right) => left.distanceM - right.distanceM)
      .slice(0, limit),
  );
}

const completedAtMs = Date.parse(snapshot.meta.completedAt);
const selectedOpportunities = snapshot.opportunities
  .filter((opportunity) => Date.parse(opportunity.endsAt) > completedAtMs)
  .sort(
    (left, right) =>
      Date.parse(left.startsAt) - Date.parse(right.startsAt) ||
      left.id.localeCompare(right.id),
  )
  .slice(0, opportunityLimit);

const placesById = new Map(snapshot.places.map((place) => [place.id, place]));
for (const opportunity of selectedOpportunities) {
  if (!opportunity.placeId) continue;
  const place = placesById.get(opportunity.placeId);
  if (place && !selectedPlaces.some((candidate) => candidate.id === place.id)) {
    selectedPlaces.push(place);
  }
}

const selectedPlaceIds = new Set(selectedPlaces.map((place) => place.id));
const selectedOpportunityIds = new Set(
  selectedOpportunities.map((opportunity) => opportunity.id),
);
const selectedSubjectIds = new Set([
  ...selectedPlaceIds,
  ...selectedOpportunityIds,
]);

function containsSelectedId(line, ids) {
  for (const id of ids) {
    if (line.includes(`'${id}'`)) return true;
  }
  return false;
}

function tableFor(line) {
  return line.match(/^INSERT INTO ([a-z_]+)/)?.[1] ?? null;
}

const statements = [];
for (const line of fullSeedLines) {
  const table = tableFor(line);
  if (!table) continue;

  if (
    table === 'sources' ||
    table === 'source_resources' ||
    table === 'source_snapshots' ||
    table === 'areas'
  ) {
    statements.push(line);
    continue;
  }
  if (
    (table === 'places' ||
      table === 'external_place_refs' ||
      table === 'restaurants') &&
    containsSelectedId(line, selectedPlaceIds)
  ) {
    statements.push(line);
    continue;
  }
  if (
    table === 'opportunities' &&
    containsSelectedId(line, selectedOpportunityIds)
  ) {
    statements.push(line);
    continue;
  }
  if (
    (table === 'evidence_assertions' || table === 'import_items') &&
    containsSelectedId(line, selectedSubjectIds)
  ) {
    statements.push(line);
  }
}

const sqlString = (value) => `'${String(value).replaceAll("'", "''")}'`;
const summary = JSON.stringify({
  deploymentSeed: 'curated',
  places: selectedPlaceIds.size,
  opportunities: selectedOpportunityIds.size,
  runtimeOverlays: ['YouBike', 'CultureNearby'],
});
const importRun = `INSERT INTO import_runs (id, area_id, importer_version, started_at, completed_at, status, summary_json) VALUES (${sqlString(snapshot.meta.runId)}, 'area_yuanshan_station_2km', ${sqlString(`${snapshot.meta.importerVersion}-sites`)}, ${sqlString(snapshot.meta.startedAt)}, ${sqlString(snapshot.meta.completedAt)}, 'COMPLETED', ${sqlString(summary)}) ON CONFLICT (id) DO UPDATE SET area_id=excluded.area_id, importer_version=excluded.importer_version, started_at=excluded.started_at, completed_at=excluded.completed_at, status=excluded.status, summary_json=excluded.summary_json;`;

const areaIndex = statements.findIndex((line) => tableFor(line) === 'areas');
statements.splice(areaIndex + 1, 0, importRun);

const output = [
  '-- Generated by scripts/build-sites-deployment-migrations.mjs.',
  '-- Curated production bootstrap; the full official snapshot remains bundled as the read fallback.',
  '-- YouBike and Culture nearby results are refreshed at request time with bounded server caches.',
  '',
  ...statements,
  '',
].join('\n');

const outputBytes = Buffer.byteLength(output);
const longestStatementBytes = Math.max(
  ...statements.map((statement) => Buffer.byteLength(statement)),
);
if (outputBytes > maxMigrationBytes) {
  throw new Error(`Sites migration is too large: ${outputBytes} bytes.`);
}
if (longestStatementBytes > maxStatementBytes) {
  throw new Error(
    `Sites migration has an oversized statement: ${longestStatementBytes} bytes.`,
  );
}

mkdirSync(outputDirectory, { recursive: true });
writeFileSync(outputPath, output, 'utf8');
console.log(
  JSON.stringify(
    {
      outputPath,
      outputBytes,
      longestStatementBytes,
      places: selectedPlaceIds.size,
      opportunities: selectedOpportunityIds.size,
      statements: statements.length,
    },
    null,
    2,
  ),
);
